drop function if exists public.mark_attendance(uuid, date, uuid, uuid, boolean, text) cascade;

drop table if exists public.app_sessions cascade;
drop table if exists public.line_pending_logins cascade;
drop table if exists public.line_auth_states cascade;
drop table if exists public.login_invites cascade;
drop table if exists public.attendance_records cascade;
