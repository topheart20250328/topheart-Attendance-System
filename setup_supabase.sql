create type public.member_gender as enum (
  'brother',
  'sister'
);

create type public.member_role as enum (
  'district_leader',
  'big_family_leader',
  'small_group_leader',
  'member',
  'best'
);

create type public.attendance_event_type as enum (
  'sunday_service',
  'small_group_fellowship'
);

create type public.attendance_status as enum (
  'unknown',
  'present',
  'absent'
);

create table public.districts (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint districts_name_not_blank check (btrim(name) <> '')
);

create table public.big_families (
  id bigint generated by default as identity primary key,
  district_id bigint not null references public.districts(id) on delete cascade,
  name text not null,
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint big_families_name_not_blank check (btrim(name) <> ''),
  constraint big_families_name_per_district unique (district_id, name)
);

create table public.small_groups (
  id bigint generated by default as identity primary key,
  district_id bigint not null references public.districts(id) on delete cascade,
  big_family_id bigint references public.big_families(id) on delete cascade,
  name text not null,
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint small_groups_name_not_blank check (btrim(name) <> '')
);

create table public.members (
  id bigint generated by default as identity primary key,
  full_name text not null,
  birthday date,
  gender public.member_gender,
  note text not null default '',
  role public.member_role not null,
  is_admin boolean not null default false,
  line_user_id text unique,
  district_id bigint references public.districts(id) on delete restrict,
  big_family_id bigint references public.big_families(id) on delete restrict,
  small_group_id bigint references public.small_groups(id) on delete restrict,
  is_active boolean not null default true,
  last_line_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint members_name_not_blank check (btrim(full_name) <> ''),
  constraint members_line_user_id_not_blank check (
    line_user_id is null or btrim(line_user_id) <> ''
  ),
  constraint members_scope_matches_role check (
    (
      role = 'district_leader'
      and district_id is not null
      and big_family_id is null
      and small_group_id is null
    )
    or (
      role = 'big_family_leader'
      and district_id is not null
      and big_family_id is not null
      and small_group_id is null
    )
    or (
      role in ('small_group_leader', 'member', 'best')
      and district_id is not null
      and small_group_id is not null
    )
  )
);

create table public.attendance_weeks (
  id bigint generated by default as identity primary key,
  week_start_date date not null unique,
  label text not null default '',
  created_at timestamptz not null default now()
);

create table public.attendance_records (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on delete cascade,
  attendance_week_id bigint not null references public.attendance_weeks(id) on delete cascade,
  event_type public.attendance_event_type not null,
  status public.attendance_status not null default 'unknown',
  note text not null default '',
  recorded_by_member_id bigint references public.members(id) on delete set null,
  recorded_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint attendance_records_one_row_per_event unique (member_id, attendance_week_id, event_type)
);

create table public.login_invites (
  id uuid primary key default gen_random_uuid(),
  member_id bigint not null references public.members(id) on delete cascade,
  invite_code text not null unique default upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8)),
  expires_at timestamptz not null,
  used_at timestamptz,
  used_by_line_user_id text,
  created_by_member_id bigint references public.members(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint login_invites_code_not_blank check (length(btrim(invite_code)) >= 6)
);

create table public.line_auth_states (
  id uuid primary key default gen_random_uuid(),
  state text not null unique,
  code_verifier text not null,
  nonce text not null,
  redirect_to text not null,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint line_auth_states_state_not_blank check (btrim(state) <> ''),
  constraint line_auth_states_code_verifier_not_blank check (btrim(code_verifier) <> ''),
  constraint line_auth_states_nonce_not_blank check (btrim(nonce) <> ''),
  constraint line_auth_states_redirect_to_not_blank check (btrim(redirect_to) <> '')
);

create table public.line_pending_logins (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  line_user_id text not null,
  display_name text not null default '',
  picture_url text not null default '',
  redirect_to text not null,
  expires_at timestamptz not null,
  consumed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint line_pending_logins_token_hash_not_blank check (btrim(token_hash) <> ''),
  constraint line_pending_logins_line_user_id_not_blank check (btrim(line_user_id) <> ''),
  constraint line_pending_logins_redirect_to_not_blank check (btrim(redirect_to) <> '')
);

create table public.app_sessions (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  member_id bigint not null references public.members(id) on delete cascade,
  line_user_id text not null,
  expires_at timestamptz not null,
  revoked_at timestamptz,
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint app_sessions_token_hash_not_blank check (btrim(token_hash) <> ''),
  constraint app_sessions_line_user_id_not_blank check (btrim(line_user_id) <> '')
);

create index idx_big_families_district_id on public.big_families (district_id);
create index idx_small_groups_district_id on public.small_groups (district_id);
